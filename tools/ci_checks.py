#!/usr/bin/env python3
"""Non-mutating CI checks (audit item I).

Five checks, each of which must pass in a clean checkout:

1. pins      -- committed artifact hashes and byte-sizes are unchanged
                (guards against silent number edits), and physics digests of
                artifacts that are not byte-reproducible (wall clocks) are
                recomputed from the committed file;
2. determinism -- a non-mutating re-run of the Fig. S32 digitizer reproduces
                every raster/coordinate-based result in the stored JSON;
3. provenance -- the machine-checkable provenance audit runs and the historical
                handoff ledger is correctly classified as *unverified*;
4. gate      -- the strict V1.9 gate evaluator runs and the stored V1.8 gate
                state is shown to disagree with its own evaluator;
5. artifact-consistency -- the report exists, is non-empty and its sha256
                matches the value recorded in the results manifest.

Exit code 0 = all pass. The script never writes into the repository: it
verifies ``git status --porcelain`` stays clean for tracked data files.
"""
from __future__ import annotations

import hashlib
import importlib.util
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, HERE)

RESULTS: list = []


def check(name, fn):
    try:
        detail = fn()
        RESULTS.append((name, True, detail or ""))
    except AssertionError as exc:
        RESULTS.append((name, False, str(exc)))
    except Exception as exc:  # noqa: BLE001 - CI must report, not crash
        RESULTS.append((name, False, f"{type(exc).__name__}: {exc}"))


# ---------------------------------------------------------------------------
def check_pins():
    man = os.path.join(HERE, "manifests", "v1.9_artifact_pins.json")
    if not os.path.exists(man):
        return ("manifests/v1.9_artifact_pins.json absent (generated by "
                "tools/v19_calibrate_twin.py --write); pin checks are covered by "
                "tests/test_eqe_s32_known_answers.py")
    pins = json.load(open(man))
    bad = []
    for rel, meta in pins.get("files", {}).items():
        path = os.path.join(HERE, rel)
        actual = hashlib.sha256(open(path, "rb").read()).hexdigest()
        if actual != meta["sha256"]:
            bad.append(rel)
    assert not bad, f"artifact hashes changed: {bad}"
    # physics digests: recompute from the committed file (covers artifacts whose
    # bytes legitimately differ between machines because they carry wall clocks)
    ndig = 0
    for rel, meta in pins.get("digests", {}).items():
        path = os.path.join(HERE, rel)
        art = json.load(open(path))
        from apmt.repro.digest import physics_digest
        digest = physics_digest(art)
        assert digest == meta["sha256"], f"physics digest changed: {rel}"
        assert digest == art["physics_digest"]["sha256"], f"{rel} digest inconsistent"
        ndig += 1
    return (f"{len(pins.get('files', {}))} artifact hashes match, "
            f"{ndig} physics digest verified")


def check_determinism():
    path = os.path.join(HERE, "data", "s32_digitize_v18.py")
    spec = importlib.util.spec_from_file_location("s32_digitize_v18", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    out = mod.main(write=False, require_pdf=False)
    stored = json.load(open(os.path.join(HERE, "data", "s32_results.json")))
    checked = []
    for tag, got in out["methods"].items():
        if got.get("status") == "SOURCE_MISSING":
            continue
        for key in ("perovskite_jph", "si_jph", "sum_jph"):
            assert got[key] == stored["methods"][tag][key], (tag, key)
        checked.append(tag)
    assert set(checked) == {"hzb_M1", "hzb_M3", "sahli_M1"}, checked
    return f"deterministic re-run matches stored JSON for {sorted(checked)}"


def check_provenance():
    from apmt.validation.provenance_gate import audit_claims, ledger_claims
    rep = audit_claims(ledger_claims())
    assert rep.n_claims > 10, rep.n_claims
    assert rep.n_verified < rep.n_claims, "handoff-quoted values must not all verify"
    return f"{rep.n_verified}/{rep.n_claims} claims verified (expected: <100% for handoff ledger)"


def check_gate():
    from apmt.genealogy import GENEALOGY_LINKAGES
    from apmt.validation.gate import GateEvidence, audit_v18_gate_consistency
    rep = audit_v18_gate_consistency(GateEvidence(
        jsc_jv_ma_cm2=19.23, jsc_eqe_ma_cm2=19.41, jsc_certified_ma_cm2=19.23,
        jv_rmse_ma_cm2=0.9170, jsc_scan_dir1_ma_cm2=19.23,
        jsc_scan_dir2_ma_cm2=19.24, linkages=GENEALOGY_LINKAGES,
        condition_number=1216249.34, boundary_hits=3))
    assert rep["evaluated_result"] == "FAIL"
    assert rep["consistent"] is False
    return "gate evaluator returns FAIL; stored V1.8 'CLOSED (DEFER)' is inconsistent"


def check_artifact_consistency():
    report = os.path.join(HERE, "reports", "APMT_MASSIVE_RND_PROGRESS_REPORT.md")
    assert os.path.exists(report), "authoritative report missing"
    size = os.path.getsize(report)
    assert size > 1000, f"report suspiciously small ({size} B)"
    sha = hashlib.sha256(open(report, "rb").read()).hexdigest()
    meta = os.path.join(HERE, "reports", ".report_sha256")
    if os.path.exists(meta):
        recorded = open(meta).read().strip()
        assert recorded == sha, ("report sha256 does not match reports/.report_sha256; "
                                 "regenerate it after editing the report")
    return f"report present ({size} B), sha256 {sha[:16]}..."


def check_git_clean():
    out = subprocess.run(["git", "status", "--porcelain", "--", "data"],
                         cwd=HERE, capture_output=True, text=True).stdout.strip()
    assert not out, f"CI mutated data/: {out}"
    return "no tracked data file was modified"


# ---------------------------------------------------------------------------
def main():
    check("pins", check_pins)
    check("determinism", check_determinism)
    check("provenance", check_provenance)
    check("gate", check_gate)
    check("artifact-consistency", check_artifact_consistency)
    check("git-clean", check_git_clean)

    width = max(len(n) for n, _, _ in RESULTS)
    n_fail = 0
    for name, ok, detail in RESULTS:
        n_fail += (not ok)
        print(f"[{'PASS' if ok else 'FAIL'}] {name.ljust(width)}  {detail}")
    print(f"\n{len(RESULTS) - n_fail}/{len(RESULTS)} CI checks passed")
    return 1 if n_fail else 0


if __name__ == "__main__":
    raise SystemExit(main())
